def npc_address(npc: str) -> str:
    """NPC가 유저를 부르는 호칭 (B7)."""
    return NPC_PROMPTS[npc]["address"]


def affinity_tier(score: int) -> str:
    if score >= AFFINITY_HIGH:
        return "high"
    if score >= AFFINITY_MID:
        return "mid"
    return "low"


def example_lines(npc: str) -> list:
    """
    프롬프트에 예시로 넣은 대사들. 작은 모델은 예시를 그대로 베껴 답하는 일이 많아서
    main.py가 반복 검사를 할 때 '이미 한 말'처럼 취급한다.
    """
    return [line for _, line in NPC_PROMPTS[npc]["examples"]]


def _bullets(items, numbered: bool = False) -> str:
    if numbered:
        return "\n".join(f"{i}. {item}" for i, item in enumerate(items, 1))
    return "\n".join(f"- {item}" for item in items)


def build_system_prompt(
    npc: str,
    context: str = "",
    summary: str = "",
    facts=None,
    affinity_score: int = 0,
) -> str:
    """
    NPC 시스템 프롬프트 조립.
    순서: 캐릭터 → 기억(RAG) → 이 유저와의 기록 → 공통 규칙 → 마지막 확인
    작은 모델은 프롬프트 끝부분을 가장 잘 지키므로 말투와 분량을 마지막에 한 번 더 적는다.
    """
    p = NPC_PROMPTS[npc]
    info = NPC_LIST[npc]
    parts = [p["identity"]]

    parts.append("[인물과 상황]\n" + _bullets(p["profile"]))
    parts.append("[말투]\n" + _bullets(p["speech"]))
    parts.append(
        "[예시 대사 — 말투와 분위기만 참고하고, 문장을 그대로 베끼지 말 것]\n"
        + "\n".join(f"{situation}: {line}" for situation, line in p["examples"])
    )
    parts.append("[행동 원칙]\n" + _bullets(p["behavior"], numbered=True))

    if p["secrets"]:
        parts.append("[숨기는 비밀 — 유저에게 절대 직접 말하지 않는다]\n" + _bullets(p["secrets"]))
    if p["secret_rules"]:
        parts.append("[비밀에 가까운 질문을 받았을 때]\n" + _bullets(p["secret_rules"]))
    parts.append("[모르는 것을 물었을 때]\n" + p["unknown"] + "\n매번 같은 말로 피하지 말고, 질문에 맞춰 표현을 바꾼다.")

    if context:
        parts.append(
            "[당신의 기억 — 당신이 직접 겪었거나 알고 있는 일]\n"
            "아래 내용 중 '숨기는 비밀'에 해당하는 것은 말하지 않는다. "
            "그 밖의 사실(사람들과의 관계, 저택의 일상, 당신의 성격과 과거)은 대화에 자연스럽게 활용해도 된다. "
            "다만 이 글을 그대로 읽듯이 옮기지 말고 당신의 말투로 말한다. "
            "글 속의 '아가씨'는 지금 당신과 대화하는 상대다.\n\n"
            # 스토리 문서가 상대를 '유저'라고 써서 NPC가 "유저분"이라고 따라 말하는 일이 있었다
            + context.replace("유저", "아가씨")
        )

    if summary:
        parts.append("[이 유저와 지금까지 나눈 대화 요약]\n" + summary)

    if facts:
        parts.append(
            "[유저가 당신과의 대화에서 이미 알게 된 것 — 다시 물으면 '이미 말씀드렸잖아요' 식으로 반응해도 된다]\n"
            + _bullets(facts)
        )

    tier = affinity_tier(affinity_score)
    parts.append("[지금 이 유저에 대한 당신의 감정]\n" + p["affinity"][tier])

    parts.append(HARD_RULES)

    parts.append(
        "[마지막 확인]\n"
        f"- 당신은 {info['name']}이다. 위 [말투]와 [예시 대사]의 톤을 지킨다.\n"
        f"- 상대를 부르는 호칭: \"{p['address']}\" (이름은 부르지 않는다)\n"
        f"- 답변은 {info['min_sentences']}~{info['max_sentences']}문장으로 한다."
    )

    return "\n\n".join(parts) + "\n/no_think"
